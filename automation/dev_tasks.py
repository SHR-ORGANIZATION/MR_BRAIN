FRAMEWORK_CREATORS = {
    "python": create_python_project,
    "react": create_react_project,
    "html": create_html_project,
    "node": create_node_project,
    "angular": create_angular_project,
    "laravel": create_laravel_project,
    "django": create_django_project,
    "vue": create_vue_project,
    "next": create_react_project,  # Uses similar Node-based approach
}


def create_project(name, framework="python", base_dir=None):
    """Create a project using the appropriate framework scaffolding."""
    framework = (framework or "python").lower().strip()
    creator = FRAMEWORK_CREATORS.get(framework)
    if not creator:
        return _build_result("Create Project", "", "failed",
                             f"Unsupported framework: {framework}. Supported: {', '.join(FRAMEWORK_CREATORS.keys())}",
                             "Project")
    return creator(name, base_dir=base_dir)


