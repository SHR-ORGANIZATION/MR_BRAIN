"""
Developer Assistance Module
Provides project scaffolding and code generation capabilities.
"""
import os
import subprocess
from pathlib import Path
from datetime import datetime


def _build_result(action, path, status, message, item_type="Project", extra=None):
    return {
        "action": action,
        "name": Path(path).name if path else "",
        "path": str(Path(path).expanduser().resolve()) if path else "",
        "type": item_type,
        "status": status,
        "message": message,
        "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "details": extra,
    }


def _ensure_dir(path):
    path = Path(path).expanduser()
    path.mkdir(parents=True, exist_ok=True)
    return path


def create_python_project(name, base_dir=None):
    """Create a Python project structure with main.py, requirements.txt, README.md."""
    base = Path(base_dir or Path.cwd()).expanduser() / name
    try:
        _ensure_dir(base)
        # main.py
        main_py = base / "main.py"
        if not main_py.exists():
            main_py.write_text(
                f'"""\\n{name} - Python Project\\nGenerated by AMAZON AI Assistant\\n"""\\n\\n\\ndef main():\\n    print("Hello from {name}!")\\n\\n\\nif __name__ == "__main__":\\n    main()\\n',
                encoding="utf-8"
            )
        # requirements.txt
        req = base / "requirements.txt"
        if not req.exists():
            req.write_text("# Add project dependencies here\n", encoding="utf-8")
        # README.md
        readme = base / "README.md"
        if not readme.exists():
            readme.write_text(
                f"# {name}\\n\\nA Python project generated by AMAZON AI Assistant.\\n\\n## Getting Started\\n\\n```bash\\npip install -r requirements.txt\\npython main.py\\n```\\n",
                encoding="utf-8"
            )
        # src folder
        _ensure_dir(base / "src")
        (base / "src" / "__init__.py").write_text("", encoding="utf-8")
        # tests folder
        _ensure_dir(base / "tests")
        (base / "tests" / "__init__.py").write_text("", encoding="utf-8")
        test_file = base / "tests" / "test_main.py"
        if not test_file.exists():
            test_file.write_text(
                '"""Tests for main module."""\\n\\n\\ndef test_placeholder():\\n    assert True\\n',
                encoding="utf-8"
            )
        return _build_result("Created Project", base, "success",
                             f"Python project '{name}' created at {base}",
                             "Python Project",
                             {"framework": "python", "files": ["main.py", "requirements.txt", "README.md", "src/", "tests/"]})
    except Exception as e:
        return _build_result("Create Project", base, "failed", str(e), "Python Project")


def create_react_project(name, base_dir=None):
    """Create a React project using create-react-app (requires Node.js)."""
    base = Path(base_dir or Path.cwd()).expanduser()
    target = base / name
    try:
        # Check if Node.js is available
        result = subprocess.run(
            ["node", "--version"], capture_output=True, text=True, timeout=10
        )
        if result.returncode != 0:
            return _build_result("Create Project", target, "failed",
                                 "Node.js is not installed. Install Node.js to create React projects.",
                                 "React Project")

        # Use npx create-react-app
        subprocess.run(
            ["npx", "--yes", "create-react-app", name],
            cwd=str(base), capture_output=True, text=True, timeout=300
        )
        if target.exists():
            return _build_result("Created Project", target, "success",
                                 f"React project '{name}' created at {target}",
                                 "React Project",
                                 {"framework": "react"})
        return _build_result("Create Project", target, "failed",
                             "create-react-app did not complete successfully",
                             "React Project")
    except subprocess.TimeoutExpired:
        return _build_result("Create Project", target, "failed",
                             "React project creation timed out", "React Project")
    except Exception as e:
        return _build_result("Create Project", target, "failed", str(e), "React Project")


def create_html_project(name, base_dir=None):
    """Create a basic HTML/CSS/JS project."""
    base = Path(base_dir or Path.cwd()).expanduser() / name
    try:
        _ensure_dir(base)
        _ensure_dir(base / "css")
        _ensure_dir(base / "js")
        _ensure_dir(base / "assets")

        # index.html
        index = base / "index.html"
        if not index.exists():
            index.write_text(
                f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{name}</title>
    <link rel="stylesheet" href="css/style.css">
</head>
<body>
    <header>
        <h1>Welcome to {name}</h1>
    </header>
    <main>
        <p>Your content goes here.</p>
    </main>
    <footer>
        <p>Generated by AMAZON AI Assistant</p>
    </footer>
    <script src="js/main.js"></script>
</body>
</html>""",
                encoding="utf-8"
            )
        # style.css
        css = base / "css" / "style.css"
        if not css.exists():
            css.write_text(
                """* { margin: 0; padding: 0; box-sizing: border-box; }
body { font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; line-height: 1.6; }
header { background: #0066cc; color: white; padding: 2rem; text-align: center; }
main { max-width: 800px; margin: 2rem auto; padding: 1rem; }
footer { background: #f8f9fa; text-align: center; padding: 1rem; margin-top: 2rem; }""",
                encoding="utf-8"
            )
        # main.js
        js = base / "js" / "main.js"
        if not js.exists():
            js.write_text(
                f'// {name} - Main JavaScript\ndocument.addEventListener("DOMContentLoaded", function() {{\n    console.log("{name} loaded!");\n}});\n',
                encoding="utf-8"
            )
        return _build_result("Created Project", base, "success",
                             f"HTML project '{name}' created at {base}",
                             "HTML Project",
                             {"framework": "html", "files": ["index.html", "css/style.css", "js/main.js", "assets/"]})
    except Exception as e:
        return _build_result("Create Project", base, "failed", str(e), "HTML Project")


def create_node_project(name, base_dir=None):
    """Create a Node.js project with package.json and basic structure."""
    base = Path(base_dir or Path.cwd()).expanduser() / name
    try:
        _ensure_dir(base)
        # package.json
        pkg = base / "package.json"
        if not pkg.exists():
            pkg.write_text(
                f'{{\n  "name": "{name}",\n  "version": "1.0.0",\n  "description": "Node.js project generated by AMAZON",\n  "main": "index.js",\n  "scripts": {{\n    "start": "node index.js",\n    "dev": "node index.js"\n  }},\n  "keywords": [],\n  "author": "",\n  "license": "ISC"\n}}\n',
                encoding="utf-8"
            )
        # index.js
        index = base / "index.js"
        if not index.exists():
            index.write_text(
                f'const http = require("http");\n\nconst server = http.createServer((req, res) => {{\n    res.writeHead(200, {{ "Content-Type": "text/plain" }});\n    res.end("Hello from {name}!\\n");\n}});\n\nconst PORT = 3000;\nserver.listen(PORT, () => {{\n    console.log(`Server running on port ${{PORT}}`);\n}});\n',
                encoding="utf-8"
            )
        # README
        readme = base / "README.md"
        if not readme.exists():
            readme.write_text(f"# {name}\n\nNode.js project.\n\n## Run\n```bash\nnpm start\n```\n", encoding="utf-8")
        return _build_result("Created Project", base, "success",
                             f"Node.js project '{name}' created at {base}",
                             "Node Project",
                             {"framework": "node", "files": ["package.json", "index.js", "README.md"]})
    except Exception as e:
        return _build_result("Create Project", base, "failed", str(e), "Node Project")


def create_angular_project(name, base_dir=None):
    """Create an Angular project (requires Angular CLI)."""
    base = Path(base_dir or Path.cwd()).expanduser()
    target = base / name
    try:
        result = subprocess.run(
            ["ng", "version"], capture_output=True, text=True, timeout=10
        )
        if result.returncode != 0:
            # Fallback: create a basic structure
            _ensure_dir(target / "src")
            (target / "package.json").write_text(
                f'{{\n  "name": "{name}",\n  "version": "0.0.0",\n  "scripts": {{\n    "start": "ng serve"\n  }}\n}}\n',
                encoding="utf-8"
            )
            return _build_result("Created Project", target, "partial",
                                 f"Angular CLI not found. Basic structure created at {target}. Install @angular/cli for full setup.",
                                 "Angular Project",
                                 {"framework": "angular"})

        subprocess.run(
            ["ng", "new", name, "--skip-git", "--skip-install"],
            cwd=str(base), capture_output=True, text=True, timeout=120
        )
        if target.exists():
            return _build_result("Created Project", target, "success",
                                 f"Angular project '{name}' created at {target}",
                                 "Angular Project",
                                 {"framework": "angular"})
        return _build_result("Create Project", target, "failed",
                             "Angular CLI did not complete", "Angular Project")
    except Exception as e:
        return _build_result("Create Project", target, "failed", str(e), "Angular Project")


