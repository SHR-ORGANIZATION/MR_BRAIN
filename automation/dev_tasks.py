def generate_code_snippet(language, snippet_type="class"):
    """Generate a code snippet for a given language and type."""
    language = (language or "python").lower().strip()
    snippet_type = (snippet_type or "class").lower().strip()
    lang_snippets = SNIPPETS.get(language, {})
    if not lang_snippets:
        return {"status": "failed", "message": f"No snippets available for {language}"}
    code = lang_snippets.get(snippet_type)
    if not code:
        available = ", ".join(lang_snippets.keys())
        return {"status": "failed", "message": f"No '{snippet_type}' snippet for {language}. Available: {available}"}
    return {"status": "success", "code": code, "language": language, "type": snippet_type}
